const MONTH = /\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*( \d{4})?\b/g

/** Rules for headers that carry a name or a month inside them. */
const RULES: [RegExp, string][] = [
  [/^Forecast for .* \(units\)$/, 'The forecast for that month, in units, as made at each run.'],
  [/^Sales team .* \(units\)$/, 'The number the sales team put forward for that run, in units.'],
  [/^Against (last month|the same month last year) \(%\)$/, 'How far the forecast is above (+) or below (−) that earlier figure.'],
  [/^Extra output a month/, 'Extra units the line makes in a month by running at the higher utilisation instead of the lower one.'],
  [/\(units per week\)$/, 'Average units sold in a week.'],
  [/against own average \(%\)$/, 'How far weekly sales in the period are above (+) or below (−) the product\'s own yearly average.'],
]

const NORM: Record<string, string> = Object.fromEntries(Object.entries(D).map(([k, v]) => [k.replace(MONTH, '{m}'), v]))

export function columnInfo(header: string): string | undefined {
  if (D[header]) return D[header]
  const n = header.replace(MONTH, '{m}')
  if (NORM[n]) return NORM[n]
  for (const [re, t] of RULES) if (re.test(header)) return t
  return undefined
}
